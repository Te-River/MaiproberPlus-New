@Immutable
data class ColorFamily(
    val color: Color,
    val onColor: Color,
    val colorContainer: Color,
    val onColorContainer: Color
)

val unspecified_scheme = ColorFamily(
    Color.Unspecified, Color.Unspecified, Color.Unspecified, Color.Unspecified
)

@Composable
fun MaiuploadTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    // Dynamic color is available on Android 12+
    dynamicColor: Boolean = true,
    content: @Composable() () -> Unit
) {
    val colorScheme = when {
        dynamicColor -> {
            val context = LocalContext.current
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        }

        darkTheme -> darkScheme
        else -> lightScheme
    }

    MaterialTheme(
        colorScheme = colorScheme,
        typography = AppTypography,
        content = content
    )
}

// ---- M3 colorScheme token helpers ----
// 这些 helper 一律走 MaterialTheme.colorScheme，在 dynamicColor 开启时也返回正确的动态色，
// 不再绕过主题直接读静态 lightScheme/darkScheme。

@Composable
fun getCardColor(): Color = MaterialTheme.colorScheme.surfaceContainerHigh

@Composable
fun getTitleFontColor(): Color = MaterialTheme.colorScheme.onSurface

@Composable
fun getDescFontColor(): Color = MaterialTheme.colorScheme.outline

@Composable
fun getButtonSelectedColor(selected: Boolean): Color =
    if (selected) MaterialTheme.colorScheme.primary
    else MaterialTheme.colorScheme.surfaceContainerHighest

fun Color.darken(factor: Float): Color {
    val red = (red * factor).coerceIn(0f, 1f)
    val green = (green * factor).coerceIn(0f, 1f)
    val blue = (blue * factor).coerceIn(0f, 1f)
    return Color(red, green, blue, alpha)
}
